package rootFinding;

public class FunctionCollection {
	public final String function1;
	public final String function2;
	public String function3;
	
	public FunctionCollection(String function1, String function2) {
		this.function1 = function1;
		this.function2 = function2;
	}
	public FunctionCollection(String function1, String function2, String function3) {
		this.function1 = function1;
		this.function2 = function2;
		this.function3 = function3;
	}
}
